/** The term as Portuguese readers say it, in the context of `question` when the answer depends on it. */
export function termIn(lang: Lang, en: string, question?: string): string {
	if (lang !== 'pt') {
		return en;
	}
	// The palate's "Confirm: Fruit" rows, stored under that key.
	if (en.startsWith('Confirm: ')) {
		return `Confirmação: ${termIn(lang, en.slice('Confirm: '.length))}`;
	}
	return (question ? PT_IN[question]?.[en] : undefined) ?? PT[en] ?? en;
}

